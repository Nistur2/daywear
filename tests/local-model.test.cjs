const assert=require('node:assert/strict');
const M=require('../dist/local-model.js');
const row=(i,rating,occasion='Casual')=>({id:String(i),name:'Look '+i,rating,occasion,features:Array(96).fill(i/10)});
assert.throws(()=>M.train([row(1,5)]),/at least 6/);
assert.throws(()=>M.train(Array.from({length:6},(_,i)=>row(i,5))),/two different ratings/);
const rows=[row(0,2),row(1,3),row(2,4),row(7,8),row(8,9),row(9,10)];
const model=M.train(rows);
assert(M.predict(model,Array(96).fill(.05),'Casual').rating<4);
assert(M.predict(model,Array(96).fill(.85),'Casual').rating>8);
assert.equal(M.predict(model,rows[0].features,'Casual').distance,0);
assert.equal(M.predict(model,rows[0].features,'Work').matchedOccasion,false);
assert.equal(M.evaluate(rows),null);
assert(Number.isFinite(M.evaluate([...rows,row(6,7)])));
assert.equal(M.valid({...rows[0],rating:11}),false);
assert.equal(M.valid({...rows[0],features:[NaN]}),false);
const black=M.features(new Uint8ClampedArray(128*192*4),128,192);
const white=M.features(new Uint8ClampedArray(128*192*4).fill(255),128,192);
assert.equal(black.length,96);assert(black.every(x=>x===0));
assert(white.every((x,i)=>i%4===3?x===0:x>.999));
assert(M.distance(black,white)>.8);
const mixed=[row(0,2,'Work'),row(1,3,'Work'),row(2,4,'Work'),row(7,8),row(8,9),row(9,10)];
assert.equal(M.predict(M.train(mixed),Array(96).fill(.8),'Work').matchedOccasion,true);
assert(M.predict(M.train(mixed),Array(96).fill(.8),'Work').nearest.every(r=>r.occasion==='Work'));
rows[0].rating=9;assert.equal(model.rows[0].rating,2);
console.log('Passed: learning from labels, minimum data, label variation, occasion fallback, model snapshot, invalid labels, image features, and evaluation.');
